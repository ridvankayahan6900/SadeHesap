val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) {
        FileInputStream(f).use { load(it) }
    }
}

fun localProp(key: String): String? {
    val v = localProps.getProperty(key)
    return if (v.isNullOrBlank()) null else v
}

